#ifndef LLVM_LIB_TARGET_IKRRISC2_IKRRISC2ISELDAGTODAG_H
#define LLVM_LIB_TARGET_IKRRISC2_IKRRISC2ISELDAGTODAG_H

#include "IKRRISC2TargetMachine.h"
#include "llvm/CodeGen/SelectionDAGISel.h"

// IKRRISC2-specific code to select IKRRISC2 machine instructions for
// SelectionDAG operations.
namespace llvm {
class IKRRISC2DAGToDAGISel : public SelectionDAGISel {
  const IKRRISC2Subtarget *Subtarget = nullptr;

public:
  IKRRISC2DAGToDAGISel() = delete;

  explicit IKRRISC2DAGToDAGISel(IKRRISC2TargetMachine &TM)
      : SelectionDAGISel(TM) {}

  bool runOnMachineFunction(MachineFunction &MF) override {
    Subtarget = &MF.getSubtarget<IKRRISC2Subtarget>();
    return SelectionDAGISel::runOnMachineFunction(MF);
  }

  void Select(SDNode *Node) override;

  // Include the pieces autogenerated from the target description.
  #include "IKRRISC2GenDAGISel.inc"

  private:
    void selectShiftLikes(SDNode *Node);
};

class IKRRISC2DAGToDAGISelLegacy : public SelectionDAGISelLegacy {
public:
  static char ID;
  explicit IKRRISC2DAGToDAGISelLegacy(IKRRISC2TargetMachine &TM);
};


} // end namespace llvm

#endif // LLVM_LIB_TARGET_IKRRISC2_IKRRISC2ISELDAGTODAG_H
