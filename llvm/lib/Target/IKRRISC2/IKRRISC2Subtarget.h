#include "llvm/MC/MCInstrItineraries.h"
#include "llvm/Support/Alignment.h"

#include <string>

#define GET_SUBTARGETINFO_HEADER
#include "IKRRISC2GenSubtargetInfo.inc"

extern bool IKRRISC2ReserveGP;
extern bool IKRRISC2NoCpload;

namespace llvm {
class IKRRISC2TargetMachine;

class IKRRISC2Subtarget : public IKRRISC2GenSubtargetInfo {
    virtual void anchor();
protected:
    IKRRISC2FrameLowering FrameLowering;
    IKRRISC2RegisterInfo RegisterInfo;
    IKRRISC2InstrInfo InstrInfo;
    IKRRISC2TargetLowering TLInfo;
    SelectionDAGTargetInfo TSInfo;
public:
  /// This constructor initializes the data members to match that
  /// of the specified triple.
    IKRRISC2Subtarget(const Triple &TT, StringRef CPU, StringRef FS,
                const IKRRISC2TargetMachine &_TM);

    

    /// Parses features string setting specified subtarget options.  Definition
    /// of function is auto generated by tblgen.
    void ParseSubtargetFeatures(StringRef CPU, StringRef TuneCPU, StringRef FS);

    const IKRRISC2FrameLowering *getFrameLowering() const override {
        return &FrameLowering;
    }

    const IKRRISC2RegisterInfo *getRegisterInfo() const override {
        return &RegisterInfo;
    }

    const IKRRISC2InstrInfo *getInstrInfo() const override {
        return &InstrInfo;
    }

    const IKRRISC2TargetLowering *getTargetLowering() const override {
      return &TLInfo;
    }
    const SelectionDAGTargetInfo *getSelectionDAGInfo() const override {
      return &TSInfo;
    }
};
} // namespace llvm

#endif // LLVM_LIB_TARGET_IKRRISC2_IKRRISC2SUBTARGET_H
