#ifndef LLVM_LIB_TARGET_IKRRISC2_MCTARGETDESC_IKRRISC2INSTPRINTER_H
#define LLVM_LIB_TARGET_IKRRISC2_MCTARGETDESC_IKRRISC2INSTPRINTER_H

#include "llvm/MC/MCInstPrinter.h"
#include "llvm/Support/Compiler.h"

namespace llvm {
class MCOperand;

class IKRRISC2InstPrinter : public MCInstPrinter {
public:
  IKRRISC2InstPrinter(const MCAsmInfo &MAI, const MCInstrInfo &MII,
                    const MCRegisterInfo &MRI)
      : MCInstPrinter(MAI, MII, MRI) {}

  // Automatically generated by tblgen.
  std::pair<const char *, uint64_t>
  getMnemonic(const MCInst &MI) const override;
  void printInstruction(const MCInst *MI, uint64_t Address,
                        const MCSubtargetInfo &STI, raw_ostream &O);
  static const char *getRegisterName(MCRegister Reg);

  // Print the given operand.
  static void printOperand(const MCOperand &MO, raw_ostream &O);

  // Override MCInstPrinter.
  void printRegName(raw_ostream &O, MCRegister Reg) override;
  void printInst(const MCInst *MI, uint64_t Address, StringRef Annot,
                 const MCSubtargetInfo &STI, raw_ostream &O) override;

private:
  void printOperand(const MCInst *MI, unsigned OpNo,
                    const MCSubtargetInfo &STI, raw_ostream &O);
};
} // end namespace llvm

#endif /* LLVM_LIB_TARGET_IKRRISC2_MCTARGETDESC_IKRRISC2INSTPRINTER_H */
