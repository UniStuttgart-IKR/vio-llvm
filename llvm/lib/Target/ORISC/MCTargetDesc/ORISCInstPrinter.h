#ifndef LLVM_LIB_TARGET_ORISC_MCTARGETDESC_ORISCINSTPRINTER_H
#define LLVM_LIB_TARGET_ORISC_MCTARGETDESC_ORISCINSTPRINTER_H

#include "llvm/MC/MCInstPrinter.h"
#include "llvm/Support/Compiler.h"

namespace llvm {
class MCOperand;

class ORISCInstPrinter : public MCInstPrinter {
public:
  ORISCInstPrinter(const MCAsmInfo &MAI, const MCInstrInfo &MII,
                    const MCRegisterInfo &MRI)
      : MCInstPrinter(MAI, MII, MRI) {}

  // Automatically generated by tblgen.
  std::pair<const char *, uint64_t>
  getMnemonic(const MCInst &MI) const override;
  bool applyTargetSpecificCLOption(StringRef Opt) override;
  void printInstruction(const MCInst *MI, uint64_t Address,
                        raw_ostream &O);
  static const char *getRegisterName(MCRegister Reg, unsigned AltIdx);

  // Print the given operand.
  void printOperand(const MCOperand &MO, raw_ostream &O);
  void printSymbol(const MCInst *MI, unsigned OpNo, raw_ostream &OS);
  void printImmBitmap(const MCInst *MI, unsigned OpNo, raw_ostream &OS);
  static const char *getRegisterName(MCRegister Reg);

  // Override MCInstPrinter.
  void printRegName(raw_ostream &O, MCRegister Reg) override;
  void printInst(const MCInst *MI, uint64_t Address, StringRef Annot,
                 const MCSubtargetInfo &STI, raw_ostream &O) override;

private:
  void printOperand(const MCInst *MI, unsigned OpNo,
                    raw_ostream &O);
};
} // end namespace llvm

#endif /* LLVM_LIB_TARGET_ORISC_MCTARGETDESC_ORISCINSTPRINTER_H */
