#ifndef LLVM_LIB_TARGET_ORISC_ORISCISELDAGTODAG_H
#define LLVM_LIB_TARGET_ORISC_ORISCISELDAGTODAG_H

#include "ORISCTargetMachine.h"
#include "llvm/CodeGen/SelectionDAGISel.h"

// ORISC-specific code to select ORISC machine instructions for
// SelectionDAG operations.
namespace llvm {
class ORISCDAGToDAGISel : public SelectionDAGISel {
  const ORISCSubtarget *Subtarget = nullptr;

public:
  ORISCDAGToDAGISel() = delete;

  explicit ORISCDAGToDAGISel(ORISCTargetMachine &TM)
      : SelectionDAGISel(TM) {}

  bool runOnMachineFunction(MachineFunction &MF) override {
    Subtarget = &MF.getSubtarget<ORISCSubtarget>();
    return SelectionDAGISel::runOnMachineFunction(MF);
  }

  void Select(SDNode *Node) override;

  // Include the pieces autogenerated from the target description.
  #include "ORISCGenDAGISel.inc"

  private:
};

class ORISCDAGToDAGISelLegacy : public SelectionDAGISelLegacy {
public:
  static char ID;
  explicit ORISCDAGToDAGISelLegacy(ORISCTargetMachine &TM);
};


} // end namespace llvm

#endif // LLVM_LIB_TARGET_ORISC_ORISCISELDAGTODAG_H
