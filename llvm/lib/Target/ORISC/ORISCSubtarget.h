#include <string>

#define GET_SUBTARGETINFO_HEADER
#include "ORISCGenSubtargetInfo.inc"

extern bool ORISCReserveGP;
extern bool ORISCNoCpload;

namespace llvm {
class ORISCTargetMachine;

class ORISCSubtarget : public ORISCGenSubtargetInfo {
    virtual void anchor();
protected:
    ORISCFrameLowering FrameLowering;
    ORISCRegisterInfo RegisterInfo;
    ORISCInstrInfo InstrInfo;
    ORISCTargetLowering TLInfo;
    SelectionDAGTargetInfo TSInfo;
public:
  /// This constructor initializes the data members to match that
  /// of the specified triple.
    ORISCSubtarget(const Triple &TT, StringRef CPU, StringRef FS,
                const ORISCTargetMachine &_TM);

    

    /// Parses features string setting specified subtarget options.  Definition
    /// of function is auto generated by tblgen.
    void ParseSubtargetFeatures(StringRef CPU, StringRef TuneCPU, StringRef FS);

    const ORISCFrameLowering *getFrameLowering() const override {
        return &FrameLowering;
    }

    const ORISCRegisterInfo *getRegisterInfo() const override {
        return &RegisterInfo;
    }

    const ORISCInstrInfo *getInstrInfo() const override {
        return &InstrInfo;
    }

    const ORISCTargetLowering *getTargetLowering() const override {
      return &TLInfo;
    }
    const SelectionDAGTargetInfo *getSelectionDAGInfo() const override {
      return &TSInfo;
    }
};
} // namespace llvm

#endif // LLVM_LIB_TARGET_ORISC_ORISCSUBTARGET_H
